const MARKS = {
  Ą: ['A', 'ogonek'], Ć: ['C', 'acute'], Ę: ['E', 'ogonek'], Ń: ['N', 'acute'],
  Ó: ['O', 'acute'], Ś: ['S', 'acute'], Ź: ['Z', 'acute'], Ż: ['Z', 'dot'],
};

export const GLYPH_H = 11;
const px = (x, y) => `M${x} ${y}h1v1h-1z`;
const cache = new Map();

export function textPath(input) {
  const text = String(input).toUpperCase();
  const hit = cache.get(text);
  if (hit) return hit;
  let x = 0;
  let d = '';
  for (const ch of text) {
    if (ch === ' ') { x += 4; continue; }
    let base = ch;
    let mark = null;
    if (MARKS[ch]) [base, mark] = MARKS[ch];
    const glyph = G[base] || G['?'];
    glyph.forEach((row, r) => {
      for (let c = 0; c < 5; c++) if (row[c] === '#') d += px(x + c, r + 3);
    });
    if (mark === 'acute') d += px(x + 3, 0) + px(x + 2, 1);
    if (mark === 'dot') d += px(x + 2, 1);
    if (mark === 'ogonek') d += px(x + 3, 10) + px(x + 4, 10);
    x += 6;
  }
  const out = { d, w: Math.max(1, x - 1) };
  cache.set(text, out);
  return out;
}

export function wrap(text, maxChars) {
  const lines = [];
  let line = '';
  for (const word of String(text).split(' ')) {
    if (!line) line = word;
    else if ((line + ' ' + word).length <= maxChars) line += ' ' + word;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}
